void display_char(uint8_t index)
{
	if(index>=0&&index<=9)index+=52;
	else if(index>=48&&index<=57)index+=4;
	else if(index>=65&&index<=90)index-=65;
	else index-=71;
    for(int row = 0; row < 8; row++)
    {
        port_write(row_v, 0x00);
        port_write(col_g, font[index][row]);
        port_write(row_v, (1 << row));
        delay_ms(2);
    }
}